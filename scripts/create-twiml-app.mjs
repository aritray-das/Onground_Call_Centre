/**
 * scripts/create-twiml-app.mjs
 *
 * One-step helper script to inspect your Twilio account, create an API Key,
 * configure the TwiML App Voice URL, and generate .env.local automatically.
 */

import fs from 'fs'
import path from 'path'
import twilio from 'twilio'

const args = process.argv.slice(2)
const accountSid = args[0] || process.env.TWILIO_ACCOUNT_SID
const authToken = args[1] || process.env.TWILIO_AUTH_TOKEN
const vercelDomain = args[2] || process.env.VERCEL_URL ? `https://${process.env.VERCEL_URL}` : ''

if (!accountSid || !authToken) {
  console.log('Usage: node scripts/create-twiml-app.mjs <ACCOUNT_SID> <AUTH_TOKEN> [VERCEL_DOMAIN]')
  process.exit(1)
}

const client = twilio(accountSid, authToken)

async function run() {
  console.log('🔍 Inspecting Twilio account...\n')

  try {
    // 1. Check Twilio Phone Numbers
    const numbers = await client.incomingPhoneNumbers.list({ limit: 5 })
    let callerId = ''
    if (numbers.length > 0) {
      callerId = numbers[0].phoneNumber
      console.log(`✅ Found Twilio Phone Number (Caller ID): ${callerId}`)
    } else {
      console.log('⚠️ No Twilio phone numbers found in account. You can get a free one in Twilio Console under Phone Numbers.')
    }

    // 2. Check Verified Caller IDs (Destinations for trial accounts)
    const verified = await client.outgoingCallerIds.list({ limit: 5 })
    let verifiedNumber = ''
    if (verified.length > 0) {
      verifiedNumber = verified[0].phoneNumber
      console.log(`✅ Found Verified Phone Number: ${verifiedNumber} (calls will route here)`)
    } else {
      console.log('ℹ️ No verified caller IDs found yet. Verify your personal mobile number in Twilio Console → Verified Caller IDs to receive test calls.')
    }

    // 3. TwiML App
    const twimlAppSid = 'AP059a4136857829bbe35f37dd55c95a04'
    const voiceUrl = `${vercelDomain.replace(/\/$/, '')}/api/voice`

    console.log(`\n⚙️ Configuring TwiML App (${twimlAppSid}) Voice Request URL to:`)
    console.log(`   ${voiceUrl}`)

    await client.applications(twimlAppSid).update({
      voiceUrl: voiceUrl,
      voiceMethod: 'POST',
    })
    console.log('✅ TwiML App Voice URL updated successfully!')

    // 4. Create an API Key for the client SDK
    console.log('\n🔑 Creating an API Key for the browser Voice SDK...')
    const apiKey = await client.newKeys.create({ friendlyName: 'OnGround Web Dialer Key' })
    console.log(`✅ API Key created: ${apiKey.sid}`)

    // 5. Generate .env.local
    const demoPasscode = 'onground2026'
    const envContent = `# Auto-generated by scripts/create-twiml-app.mjs
TWILIO_ACCOUNT_SID=${accountSid}
TWILIO_API_KEY_SID=${apiKey.sid}
TWILIO_API_KEY_SECRET=${apiKey.secret}
TWILIO_TWIML_APP_SID=${twimlAppSid}
TWILIO_CALLER_ID=${callerId}
TWILIO_AUTH_TOKEN=${authToken}
DEMO_PASSCODE=${demoPasscode}
${verifiedNumber ? `DEMO_ROUTE_TO=${verifiedNumber}` : '# DEMO_ROUTE_TO='}
DEMO_ALLOWED_NUMBERS=${verifiedNumber || '+919999999999'}
`

    const envPath = path.resolve(process.cwd(), '.env.local')
    fs.writeFileSync(envPath, envContent, 'utf8')
    console.log(`\n📄 Created ${envPath} successfully!`)

    console.log('\n──────────────────────────────────────────────────────────')
    console.log('🎉 ALL TWILIO CONFIGURATION COMPLETE!')
    console.log('──────────────────────────────────────────────────────────')
    console.log(`Demo Passcode for web app: ${demoPasscode}`)
    console.log(`Caller ID: ${callerId || '(Please claim a number in Twilio Console)'}`)
    console.log(`Destination Phone: ${verifiedNumber || '(Please add your phone in Verified Caller IDs)'}`)
    console.log('──────────────────────────────────────────────────────────\n')

  } catch (err) {
    console.error('❌ Error during setup:', err.message)
    if (err.code) console.error(`Error Code: ${err.code}`)
  }
}

run()
